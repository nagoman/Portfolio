      const response = await fetch('/api/contact', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(Object.fromEntries(formData.entries())),
      });
      const responseText = await response.text();
      let result;
      try {
        result = JSON.parse(responseText);
      } catch {
        throw new Error(response.ok ? 'The server returned an unexpected response.' : `The contact service is unavailable (${response.status}). Please try again shortly.`);
      }
      if (!response.ok) throw new Error(result.error || 'Unable to send your inquiry.');
      form.reset();
      setFormStatus({ type: 'success', message: 'Thank you. Your inquiry has been received.' });
